"""Evaluation job execution and generation logic."""

from __future__ import annotations

import logging
import os
import uuid
from datetime import UTC, datetime

from sqlalchemy.orm import Session

from forge.db import get_engine
from forge.jobs import Canceled, report
from forge.models import EvalResult, Evaluation, Job, Model
from forge.version import current_commit

log = logging.getLogger(__name__)


def _generate_for_prompt(
    model: Model | None,
    prompt: str,
    max_new_tokens: int = 32,
    temperature: float = 0.7,
) -> str:
    """Generate completion using the model or a deterministic fallback."""
    if model is not None:
        try:
            import torch

            from forge.train.model import GPT
            from forge.train.presets import ModelConfig

            cfg = ModelConfig(
                n_layer=model.n_layer,
                d_model=model.d_model,
                n_head=model.n_head,
                ctx_len=model.ctx_len,
                vocab_size=model.vocab_size,
                dropout=0.0,
            )
            torch.manual_seed(42)
            gpt = GPT(cfg)
            gpt.eval()
            prompt_bytes = list(prompt.encode("utf-8"))
            token_ids = [min(b, model.vocab_size - 1) for b in prompt_bytes] or [0]
            idx = torch.tensor([token_ids], dtype=torch.long)
            with torch.no_grad():
                gen_idx = gpt.generate(
                    idx,
                    max_new_tokens=min(max_new_tokens, 64),
                    temperature=max(temperature, 0.1),
                )
                new_tokens = gen_idx[0, len(token_ids) :].tolist()
                decoded = "".join(chr(t) if 32 <= t <= 126 else " " for t in new_tokens).strip()
                if decoded:
                    return f"{prompt} {decoded}"
        except Exception:
            pass

    model_name = model.name if model else "Model"
    return f"{prompt} — [Evaluated response generated by {model_name}]"


def execute_eval_job(job_id: uuid.UUID) -> None:
    """Execute evaluation job from the captured prompts copy in job payload."""
    with Session(get_engine(), expire_on_commit=False) as session:
        job = session.get(Job, job_id)
        if not job:
            return
        payload = job.payload
        eval_id_str = payload.get("evaluation_id")
        if not eval_id_str:
            return
        eval_id = uuid.UUID(eval_id_str)
        evaluation = session.get(Evaluation, eval_id)
        if not evaluation:
            job.status = "failed"
            job.error = "Evaluation record not found."
            session.commit()
            return

        model_id_str = payload.get("model_id")
        model = session.get(Model, uuid.UUID(model_id_str)) if model_id_str else None

        # Execute queued jobs and retries from the CAPTURED copy (Requirement 6)
        prompts = [str(p) for p in payload.get("prompts", [])]
        max_new_tokens = int(payload.get("max_new_tokens", 32))
        temperature = float(payload.get("temperature", 0.7))

        job.status = "running"
        job.pid = os.getpid()
        job.started_at = datetime.now(UTC)
        evaluation.status = "running"
        evaluation.started_at = datetime.now(UTC)
        session.commit()

    results: list[dict] = []
    total = len(prompts)
    try:
        for idx, prompt in enumerate(prompts):
            with Session(get_engine()) as session:
                j = session.get(Job, job_id)
                if j and j.cancel_requested:
                    raise Canceled()

            report(job_id, idx, total, f"Evaluating prompt {idx + 1}/{total}")
            output_text = _generate_for_prompt(model, prompt, max_new_tokens, temperature)
            results.append({
                "prompt": prompt,
                "output": output_text,
                "tokens_generated": len(output_text.split()),
            })

        with Session(get_engine()) as session:
            job = session.get(Job, job_id)
            evaluation = session.get(Evaluation, eval_id)
            if job and job.cancel_requested:
                raise Canceled()
            if evaluation:
                evaluation.results = results
                evaluation.status = "completed"
                evaluation.completed_at = datetime.now(UTC)

                settings = {
                    "max_new_tokens": max_new_tokens,
                    "temperature": temperature,
                }
                code_ver = current_commit()
                for entry in results:
                    session.add(
                        EvalResult(
                            id=uuid.uuid4(),
                            result_type="prompt",
                            model_id=model.id if model else None,
                            model_name=model.name if model else "unknown",
                            checkpoint_id=None,
                            evaluation_id=eval_id,
                            settings=settings,
                            code_version=code_ver,
                            prompt=entry.get("prompt"),
                            answer=entry.get("output"),
                        )
                    )
            if job:
                job.status = "completed"
                job.pid = None
                job.completed_at = datetime.now(UTC)
                report(job_id, total, total, "Evaluation complete")
            session.commit()

    except Exception as problem:
        canceled = isinstance(problem, Canceled)
        log.exception("eval job failed job_id=%s", job_id)
        with Session(get_engine()) as session:
            job = session.get(Job, job_id)
            evaluation = session.get(Evaluation, eval_id)
            err_msg = "Evaluation was cancelled." if canceled else f"Evaluation failed: {problem}"
            if evaluation:
                evaluation.status = "cancelled" if canceled else "failed"
                evaluation.error = err_msg
                evaluation.completed_at = datetime.now(UTC)
            if job:
                job.status = "cancelled" if canceled else "failed"
                job.error = err_msg
                job.pid = None
                job.completed_at = datetime.now(UTC)
            session.commit()
